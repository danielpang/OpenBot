// Bundles the Mac app's office (apps/web) for the Bots screen's end of list easter egg.
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const stubs = {
  '@tanstack/react-router': 'office/router-stub.ts',
  '@openbots/ui': 'office/ui-stub.ts',
  '@openbots/avatars/react': 'office/avatars-react-stub.ts',
  '@openbots/shared': 'office/shared-stub.ts',
};
// apps/web resolves its own React; one copy for the whole page, the one react-dom uses.
const require = createRequire(import.meta.url);
const packageDir = (name) => dirname(require.resolve(`${name}/package.json`));
const result = await build({
  absWorkingDir: root,
  entryPoints: ['office/browser.tsx'],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'safari17',
  jsx: 'automatic',
  minify: true,
  conditions: ['@openbots/source'],
  alias: { react: packageDir('react'), 'react-dom': packageDir('react-dom') },
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'inline',
  plugins: [
    {
      name: 'office-stubs',
      setup(build) {
        const filter = new RegExp(
          `^(${Object.keys(stubs)
            .map((name) => name.replace(/[/.]/g, '\\$&'))
            .join('|')})$`,
        );
        build.onResolve({ filter }, (args) => ({ path: `${root}${stubs[args.path]}` }));
      },
    },
  ],
});
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
await writeFile(
  new URL('../src/office/generated.ts', import.meta.url),
  `// Generated by scripts/build-office.mjs from apps/web's office.\n// prettier-ignore\nexport const OFFICE_BUNDLE = ${JSON.stringify(script)};\n`,
);
