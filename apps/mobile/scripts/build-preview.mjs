import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/preview/browser.ts'],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'browser',
  target: 'safari17',
  minify: true,
  legalComments: 'inline',
});
const notices = await readFile(new URL('../native/novnc-LICENSE.txt', import.meta.url), 'utf8');
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
await writeFile(
  new URL('../src/preview/generated.ts', import.meta.url),
  `// Generated by scripts/build-preview.mjs. Includes noVNC (MPL-2.0); see native/novnc-LICENSE.txt.\n// prettier-ignore\nexport const PREVIEW_BROWSER_BUNDLE = ${JSON.stringify(script)};\n// prettier-ignore\nexport const PREVIEW_THIRD_PARTY_NOTICES = ${JSON.stringify(notices)};\n`,
);
